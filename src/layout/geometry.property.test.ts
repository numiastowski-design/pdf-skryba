/**
 * Fuzz testing, target 1 of 4 (docs/FUZZ-TESTING.md [purged 27/09/2026, git history] §6, promoted from "later"
 * now that the geometry it anticipated actually exists). `fast-check` core
 * package only (no `@fast-check/vitest` wrapper, per FUZZ-TESTING.md [purged 27/09/2026, git history] §7).
 *
 * THE PROPERTY (written before any test, per the user's explicit method —
 * "the property is already written" per FUZZ-TESTING.md [purged 27/09/2026, git history] §6, this file just
 * makes it executable): the conservation invariant on `assignFragmentsToCells`
 * — every input fragment lands in exactly one place (a single cell OR
 * `outside`, never both, never neither), `ambiguous` is only ever a flag on
 * top of a placement (never a THIRD bucket), and no cell is invented outside
 * the grid's own declared row/col count. Deliberately split into two
 * properties: one over grids that respect `TableGrid`'s own documented
 * contract (≥2 boundaries per axis, sorted per axis), and one that
 * DELIBERATELY violates it (degenerate/malformed grids — zero or one
 * boundary, unsorted, duplicated) since nothing in the type system or the
 * function itself enforces that contract at runtime, and
 * FUZZ-TESTING.md [purged 27/09/2026, git history] §6 explicitly calls out unsorted boundaries,
 * duplicated boundaries and a degenerate grid as things to throw at it.
 *
 * Coordinates are deliberately BIASED toward the grid's own boundary values
 * (not purely uniform random) — FUZZ-TESTING.md [purged 27/09/2026, git history] §6's own last bullet,
 * a fragment lying exactly on a boundary (strict equality).
 * With continuous random doubles, an exact equality has ~zero probability
 * of ever being generated by chance; a first version of this file without
 * this bias ran green in 100/100 cases without ever exercising that branch
 * at all — not evidence of correctness, just evidence of a generator that
 * never tried. FUZZ-TESTING.md [purged 27/09/2026, git history] §7 warns about a weak property test failing
 * because its generator produced anything at all — the failure mode here was the mirror image, a generator too weak
 * to ever reach the interesting case at all.
 */

import fc from "fast-check";
import { describe, expect, it } from "vitest";
import { assignFragmentsToCells, type Fragment, type TableGrid } from "./geometry";

// PDF coordinates in practice: bounded, finite. Some fragments deliberately
// land outside a page-sized range too (a plausible degenerate case: a
// mis-parsed transform pushing a fragment far off-page), not just inside it.
const coordArbitrary = fc.double({ min: -500, max: 2000, noNaN: true });
const sizeArbitrary = fc.double({ min: 0, max: 200, noNaN: true }); // real fragments never have negative width/height

/** Fragments for a GIVEN grid, with x/y biased toward the grid's own
 *  boundary values (see file header) so the exact-equality / straddle
 *  branches actually get exercised, not just avoided by chance. */
function fragmentsForGrid(grid: TableGrid): fc.Arbitrary<Fragment[]> {
  const boundaryValues = [...grid.rowBoundaries, ...grid.colBoundaries];
  const coordBiasedToBoundaries: fc.Arbitrary<number> =
    boundaryValues.length > 0
      ? fc.oneof({ weight: 2, arbitrary: coordArbitrary }, { weight: 1, arbitrary: fc.constantFrom(...boundaryValues) })
      : coordArbitrary;
  const fragmentArbitrary: fc.Arbitrary<Fragment> = fc.record({
    text: fc.string({ minLength: 0, maxLength: 20 }),
    x: coordBiasedToBoundaries,
    y: coordBiasedToBoundaries,
    width: sizeArbitrary,
    height: sizeArbitrary,
  });
  return fc.array(fragmentArbitrary, { minLength: 0, maxLength: 12 });
}

/** Every fragment placed in `cells` exactly once, `outside` accounts for the
 *  rest, `ambiguous` is a subset of what's IN cells (never a fragment that's
 *  neither placed nor outside), and no cell array outside the grid's own
 *  declared [rows]x[cols] shape exists — the shared assertion body for both
 *  properties below (well-formed and degenerate grids alike: "never invents,
 *  never loses, never duplicates" doesn't get to have exceptions just
 *  because the grid itself is malformed — a malformed grid should route
 *  everything to `outside`, not corrupt the accounting). */
function assertConservation(fragments: readonly Fragment[], grid: TableGrid): void {
  const result = assignFragmentsToCells(fragments, grid);

  const rows = grid.rowBoundaries.length - 1;
  const cols = grid.colBoundaries.length - 1;
  // A grid with no real cells on EITHER axis (post-fix, STATUS.md 04/09/2026)
  // short-circuits to a fully empty `cells` matrix — not "the other axis's
  // own row/col count still allocated" — everything routes to `outside`.
  if (rows < 1 || cols < 1) {
    expect(result.cells).toEqual([]);
  } else {
    expect(result.cells.length).toBe(rows);
    for (const row of result.cells) expect(row.length).toBe(cols);
  }

  const placedInCells = result.cells.flat().flat();
  const allAccounted = [...placedInCells, ...result.outside];
  // Reference-identity accounting (fragments are unique object instances in
  // this test, never deep-equal duplicates by construction) — every input
  // object appears in the accounted set EXACTLY once: nothing lost,
  // nothing duplicated, nothing invented (no extra fragments appear either).
  expect(allAccounted).toHaveLength(fragments.length);
  for (const f of fragments) {
    const countInCells = placedInCells.filter((p) => p === f).length;
    const countInOutside = result.outside.filter((p) => p === f).length;
    expect(countInCells + countInOutside).toBe(1);
  }

  // ambiguous is a flag on a PLACEMENT, never a third bucket — every
  // ambiguous fragment must also be one of the ones placed in a cell.
  for (const f of result.ambiguous) {
    expect(placedInCells).toContain(f);
  }
}

describe("assignFragmentsToCells — conservation invariant (fuzz target 1/4, well-formed grids)", () => {
  it("never loses, duplicates, or invents a fragment/cell, for any grid respecting TableGrid's own documented contract", () => {
    const wellFormedGridArbitrary: fc.Arbitrary<TableGrid> = fc
      .tuple(
        fc.array(coordArbitrary, { minLength: 2, maxLength: 5 }),
        fc.array(coordArbitrary, { minLength: 2, maxLength: 5 }),
      )
      .map(([rowsRaw, colsRaw]) => ({
        rowBoundaries: [...rowsRaw].sort((a, b) => b - a), // descending, per TableGrid's own doc
        colBoundaries: [...colsRaw].sort((a, b) => a - b), // ascending
      }));

    fc.assert(
      fc.property(
        wellFormedGridArbitrary.chain((grid) => fc.tuple(fc.constant(grid), fragmentsForGrid(grid))),
        ([grid, fragments]) => assertConservation(fragments, grid),
      ),
    );
  });
});

describe("assignFragmentsToCells — conservation invariant under DEGENERATE grids (fuzz target 1/4, FUZZ-TESTING.md [purged 27/09/2026, git history] §6)", () => {
  it("holds for 0, 1, 2+ boundaries per axis, unsorted, or duplicated boundary values", () => {
    // Degenerate on purpose: 0-3 boundaries (below the real MIN_BOUNDARIES=2
    // gate that the two builder functions enforce — but assignFragmentsToCells
    // itself is a standalone exported function with no such guard), NOT
    // necessarily sorted, NOT necessarily deduplicated. Previously excluded
    // "exactly 1 boundary on some axis" via fc.pre (a confirmed crash,
    // STATUS.md 04/09/2026) — fixed (assignFragmentsToCells now routes
    // everything to `outside` when an axis has no real cells) and widened
    // back to the full degenerate space; see the dedicated regression test
    // below for the exact fixed case.
    const degenerateBoundaryArbitrary = fc.array(coordArbitrary, { minLength: 0, maxLength: 3 });
    const degenerateGridArbitrary: fc.Arbitrary<TableGrid> = fc
      .tuple(degenerateBoundaryArbitrary, degenerateBoundaryArbitrary)
      .map(([rowBoundaries, colBoundaries]) => ({ rowBoundaries, colBoundaries }));

    fc.assert(
      fc.property(
        degenerateGridArbitrary.chain((grid) => fc.tuple(fc.constant(grid), fragmentsForGrid(grid))),
        ([grid, fragments]) => assertConservation(fragments, grid),
      ),
    );
  });
});

describe("assignFragmentsToCells — regression: fixed crash on a single-boundary axis (STATUS.md 04/09/2026, found by fuzzing, fixed same day)", () => {
  it("routes every fragment to `outside` instead of crashing when either axis has EXACTLY one boundary (fast-check's own minimal shrunk counterexample from the original finding)", () => {
    // Root cause (was): `colBoundaries.length === 1` makes `cols = 0`, so
    // every `cells[row]` was an empty array `[]` — but `xMin === xMax` (the
    // single boundary) still let a fragment whose x EXACTLY equals it pass
    // the `insideBounds` check, so the function proceeded to
    // `cells[clampedRow]![clampedCol]!.push(f)` against a row with no valid
    // index at all. Same failure mode symmetrically for
    // `rowBoundaries.length === 1`. Fix: a grid with `rows < 1 || cols < 1`
    // has no real cells to explain anything with — every fragment now
    // routes to `outside`, same treatment as a fragment outside a
    // well-formed grid's own bounds. Real callers never hit this (both grid
    // builders enforce MIN_BOUNDARIES=2), but the function itself is
    // exported with no such contract of its own.
    const grid: TableGrid = { rowBoundaries: [10, 5, 0], colBoundaries: [7] };
    const fragments: Fragment[] = [{ text: "", x: 7, y: 5, width: 0, height: 0 }];

    expect(() => assignFragmentsToCells(fragments, grid)).not.toThrow();
    const result = assignFragmentsToCells(fragments, grid);
    expect(result).toEqual({ cells: [], ambiguous: [], outside: fragments });
  });
});
